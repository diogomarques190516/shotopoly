export type Locale ='pt' |'en' |'fr' |'de' |'es';
const SUPPORTED: Locale[] = ['pt','en','fr','de','es'];

export function getLocale(): Locale {
  try {
    const raw = Intl.DateTimeFormat().resolvedOptions().locale ??'';
    const lang = raw.split('-')[0].toLowerCase() as Locale;
    if (SUPPORTED.includes(lang)) return lang;
  } catch {}
  return'pt';
}

export function t(key: string, locale: Locale, vars?: Record<string, string | number>): string {
  let str = (UI[locale] as any)[key] ?? (UI.pt as any)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) str = str.replace(`{${k}}`, String(v));
  return str;
}

export function getEventMessage(effect: string, locale: Locale): string | undefined {
  return (EVENT_MESSAGES[effect] as any)?.[locale];
}

